def main():
    input_file = '近60天价格异常-20260528.xlsx'
    output_file = '近60天价格异常-含项目信息-20260528.xlsx'
    
    wb = openpyxl.load_workbook(input_file)
    ws = wb.active
    
    # Add new columns: 合同编号, 项目名称
    max_col = ws.max_column
    ws.cell(row=1, column=max_col + 1, value='合同编号').font = Font(bold=True, color='FFFFFF')
    ws.cell(row=1, column=max_col + 1).fill = PatternFill(start_color='2F5496', end_color='2F5496', fill_type='solid')
    ws.cell(row=1, column=max_col + 2, value='项目名称').font = Font(bold=True, color='FFFFFF')
    ws.cell(row=1, column=max_col + 2).fill = PatternFill(start_color='2F5496', end_color='2F5496', fill_type='solid')
    
    ws.column_dimensions[openpyxl.utils.get_column_letter(max_col + 1)].width = 20
    ws.column_dimensions[openpyxl.utils.get_column_letter(max_col + 2)].width = 36
    
    matched = 0
    for row in range(2, ws.max_row + 1):
        po = str(ws.cell(row=row, column=3).value or '')  # col 3 = 采购订单号
        if po in PO_PROJECT_MAP:
            contract_no, project_name = PO_PROJECT_MAP[po]
            ws.cell(row=row, column=max_col + 1, value=contract_no)
            ws.cell(row=row, column=max_col + 2, value=project_name)
            matched += 1
        else:
            ws.cell(row=row, column=max_col + 1, value='（待查询）')
            ws.cell(row=row, column=max_col + 2, value='（待查询）')
    
    wb.save(output_file)
    print(f"完成！匹配 {matched}/{ws.max_row - 1} 条")
    print(f"缺失映射的 PO 数量: {len(MISSING_POS)}")
    print(f"输出文件: {output_file}")

if __name__ == '__main__':
    main()
